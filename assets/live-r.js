// Browser exercises use a pinned webR release; ordinary book code stays copyable.
let runtime;
let queue = Promise.resolve();
async function getR() {
  if (!runtime) runtime = (async () => {
    const { WebR, ChannelType } = await import('https://webr.r-wasm.org/v0.6.0/webr.mjs');
    const r = new WebR({ channelType: ChannelType.PostMessage, interactive: false });
    await r.init();
    return r;
  })().catch(error => { runtime = undefined; throw error; });
  return runtime;
}
for (const [index, box] of [...document.querySelectorAll('.live-r')].entries()) {
  const source = box.querySelector('pre code');
  if (!source) continue;
  const original = source.textContent.trim();
  const mount = document.createElement('div');
  const codeBlock = box.querySelector('div.sourceCode') || source.closest('pre');
  codeBlock.replaceWith(mount);
  const editor = document.createElement('textarea');
  editor.value = original;
  editor.spellcheck = false;
  editor.rows = Math.min(20, original.split('\n').length + 1);
  editor.id = `live-r-${index}`;
  editor.setAttribute('aria-label', 'Editable R code');
  const label = document.createElement('label');
  label.htmlFor = editor.id;
  label.textContent = 'R code · edit, run, explore';
  const toolbar = document.createElement('div');
  toolbar.className = 'live-toolbar';
  const status = document.createElement('span');
  status.className = 'live-status';
  status.setAttribute('role', 'status');
  status.textContent = 'Ready · R loads on first run';
  const output = document.createElement('pre');
  output.className = 'live-output';
  output.setAttribute('aria-label', 'R console output');
  output.setAttribute('aria-live', 'polite');
  output.hidden = true;
  const plots = document.createElement('div');
  plots.className = 'live-plots';
  const button = (text, action) => {
    const b = document.createElement('button');
    b.type = 'button'; b.textContent = text;
    b.addEventListener('click', action); toolbar.append(b); return b;
  };
  const run = button('▶ Run R', () => {
    const code = editor.value;
    run.disabled = true;
    status.textContent = 'Loading / running R…';
    output.hidden = true; plots.replaceChildren();
    queue = queue.then(async () => {
      let shelter;
      try {
        const r = await getR();
        shelter = await new r.Shelter();
        const result = await shelter.captureR(code, {
          withAutoprint: true, captureGraphics: { width: 700, height: 440 },
        });
        output.textContent = result.output.map(x => {
          if (x.type === 'stdout' || x.type === 'stderr') return x.data;
          if (x.data?.message) return `${x.type}: ${x.data.message}\n`;
          return '';
        }).join('\n') || 'Code completed without printed output.';
        for (const img of result.images) {
          const canvas = document.createElement('canvas');
          canvas.width = img.width; canvas.height = img.height;
          canvas.setAttribute('role', 'img');
          canvas.setAttribute('aria-label', 'Plot generated by the R code above');
          canvas.getContext('2d').drawImage(img, 0, 0);
          plots.append(canvas); img.close();
        }
        status.textContent = 'Completed · change a value and run again';
      } catch (error) {
        output.textContent = `R could not complete this code.\n${error.message}\n\nCheck the code and try again. First run needs an internet connection to download R.`;
        status.textContent = 'Check the message below';
      } finally {
        if (shelter) await shelter.purge();
        output.hidden = false; run.disabled = false;
      }
    }).catch(error => { status.textContent = error.message; run.disabled = false; });
  });
  button('Reset code', () => {
    editor.value = original; output.hidden = true; plots.replaceChildren();
    status.textContent = 'Original code restored';
  });
  button('Copy code', async () => {
    try { await navigator.clipboard.writeText(editor.value); status.textContent = 'Code copied'; }
    catch { editor.focus(); editor.select(); status.textContent = 'Code selected · press Ctrl+C or ⌘C'; }
  });
  mount.append(label, editor, toolbar, status, output, plots);
}
